/**
 * Companion-app Pairing & Merchant Device Management screen.
 *
 * Implements Contract B (`POST /v1/keyboard/pairing/claim`) and handles deep links
 * of the form `aulaa-keyboard://pair?code=ABCDEFGH` generated by Contract A
 * (`POST /v1/keyboard/pairing/start`).
 */
@Composable
fun AulaaPairingContent(
    api: AulaaApi,
    pairingStore: PairingStore,
    initialPairingCode: String? = null,
    modifier: Modifier = Modifier,
) {
    val p = AulaaTheme.palette
    val scope = rememberCoroutineScope()

    val session by pairingStore.sessionFlow.collectAsState()
    val apiBaseUrl by pairingStore.apiBaseUrlFlow.collectAsState()

    var codeInput by remember(initialPairingCode) {
        mutableStateOf(extractCodeFromInput(initialPairingCode.orEmpty()))
    }
    var deviceNameInput by remember {
        mutableStateOf(defaultDeviceName())
    }
    var serverUrlInput by remember(apiBaseUrl) {
        mutableStateOf(apiBaseUrl)
    }
    var showServerConfig by remember { mutableStateOf(false) }

    var claiming by remember { mutableStateOf(false) }
    var syncingProjects by remember { mutableStateOf(false) }
    var statusMessage by remember { mutableStateOf<String?>(null) }
    var isError by remember { mutableStateOf(false) }

    fun submitClaim(rawCode: String) {
        val cleanCode = extractCodeFromInput(rawCode)
        val cleanDevice = deviceNameInput.trim().take(100)
        if (cleanCode.isBlank()) {
            isError = true
            statusMessage = "Masukkan kode pairing 8 karakter dari Dashboard Aulaa."
            return
        }
        if (cleanDevice.isBlank()) {
            isError = true
            statusMessage = "Nama perangkat wajib diisi (maks 100 karakter)."
            return
        }
        pairingStore.setApiBaseUrl(serverUrlInput)
        claiming = true
        statusMessage = null
        isError = false
        scope.launch {
            runCatching {
                api.claimPairing(cleanCode, cleanDevice)
            }.onSuccess { claimed ->
                claiming = false
                codeInput = ""
                isError = false
                statusMessage = "Berhasil terhubung ke ${claimed.merchant.name} sebagai ${claimed.device.name}."
            }.onFailure { err ->
                claiming = false
                isError = true
                statusMessage = err.message ?: "Gagal melakukan klaim pairing."
            }
        }
    }

    // Auto-claim when opened via QR deep link `aulaa-keyboard://pair?code=ABCDEFGH`
    LaunchedEffect(initialPairingCode) {
        val codeFromQr = extractCodeFromInput(initialPairingCode.orEmpty())
        if (codeFromQr.isNotBlank()) {
            codeInput = codeFromQr
            submitClaim(codeFromQr)
        }
    }

    Column(
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 8.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp),
    ) {
        // Header banner
        Row(
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier
                .fillMaxWidth()
                .background(p.card, RoundedCornerShape(AulaaTheme.radiusLg))
                .border(BorderStroke(1.dp, p.border), RoundedCornerShape(AulaaTheme.radiusLg))
                .padding(14.dp),
        ) {
            Box(
                Modifier
                    .size(38.dp)
                    .background(
                        Brush.linearGradient(listOf(p.brandLight, p.brandDeep)),
                        RoundedCornerShape(10.dp),
                    ),
                contentAlignment = Alignment.Center,
            ) {
                Text("a", color = p.onBrand, fontSize = 21.sp, fontWeight = FontWeight.Medium)
            }
            Spacer(Modifier.width(12.dp))
            Column(Modifier.weight(1f)) {
                Text(
                    "Integrasi Pembayaran Aulaa",
                    color = p.foreground,
                    fontSize = 15.sp,
                    fontWeight = FontWeight.Medium,
                )
                Text(
                    if (session != null) {
                        "Terhubung ke ${session!!.merchant.name}"
                    } else {
                        "Belum terhubung · Pair dari Dashboard Web"
                    },
                    color = if (session != null) p.brandDeep else p.mutedForeground,
                    fontSize = 12.5.sp,
                )
            }
        }

        if (statusMessage != null) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier
                    .fillMaxWidth()
                    .background(if (isError) p.muted else p.brandTint, RoundedCornerShape(AulaaTheme.radius))
                    .border(
                        BorderStroke(1.dp, if (isError) p.border else p.brandMid),
                        RoundedCornerShape(AulaaTheme.radius),
                    )
                    .padding(horizontal = 12.dp, vertical = 10.dp),
            ) {
                Text(
                    text = statusMessage!!,
                    color = if (isError) p.foreground else p.brandDeep,
                    fontSize = 12.5.sp,
                    modifier = Modifier.weight(1f),
                )
                Spacer(Modifier.width(8.dp))
                Text(
                    "✕",
                    color = p.mutedForeground,
                    fontSize = 12.sp,
                    modifier = Modifier.clickable { statusMessage = null },
                )
            }
        }

        if (session != null) {
            PairedSessionCard(
                session = session!!,
                syncing = syncingProjects,
                onSyncProjects = {
                    syncingProjects = true
                    statusMessage = null
                    scope.launch {
                        runCatching { api.listProjects() }
                            .onSuccess { list ->
                                syncingProjects = false
                                isError = false
                                statusMessage = "Sinkronisasi berhasil (${list.size} project ditemukan)."
                            }
                            .onFailure { err ->
                                syncingProjects = false
                                isError = true
                                statusMessage = err.message ?: "Gagal menyinkronkan project."
                            }
                    }
                },
                onUnpair = {
                    pairingStore.clear()
                    isError = false
                    statusMessage = "Perangkat telah diputuskan dari akun merchant."
                },
            )
        }

        // Claim / Re-pair Card
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(p.card, RoundedCornerShape(AulaaTheme.radiusLg))
                .border(BorderStroke(1.dp, p.border), RoundedCornerShape(AulaaTheme.radiusLg))
                .padding(14.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Text(
                text = if (session == null) "Hubungkan Perangkat Baru" else "Ganti / Hubungkan Ulang Perangkat",
                color = p.foreground,
                fontSize = 14.5.sp,
                fontWeight = FontWeight.Medium,
            )
            Text(
                text = "1. Buka Dashboard Web Aulaa → Pengaturan Akun → Perangkat Keyboard.\n" +
                    "2. Klik \"Tambah Perangkat\" untuk mendapatkan kode 8 karakter (mis. ABCD-EFGH) atau scan QR.\n" +
                    "3. Masukkan kode di bawah sebelum kedaluwarsa (3 menit).",
                color = p.mutedForeground,
                fontSize = 12.sp,
                lineHeight = 17.sp,
            )

            Column(verticalArrangement = Arrangement.spacedBy(5.dp)) {
                FieldLabel("KODE PAIRING (8 KARAKTER ATAU URI QR)")
                PairingTextField(
                    value = codeInput,
                    onValueChange = { codeInput = extractCodeFromInput(it) },
                    placeholder = "ABCD-EFGH",
                    capitalization = KeyboardCapitalization.Characters,
                )
            }

            Column(verticalArrangement = Arrangement.spacedBy(5.dp)) {
                FieldLabel("NAMA PERANGKAT (MAKS 100 KARAKTER)")
                PairingTextField(
                    value = deviceNameInput,
                    onValueChange = { deviceNameInput = it.take(100) },
                    placeholder = "mis. Pixel 8 Pro",
                )
            }

            // Collapsible server URL config
            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.clickable { showServerConfig = !showServerConfig },
            ) {
                Text(
                    text = if (showServerConfig) "Pengaturan Server API ▴" else "Pengaturan Server API ▾",
                    color = p.brandDeep,
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Medium,
                )
                Spacer(Modifier.width(6.dp))
                Text(
                    text = "(${serverUrlInput.removePrefix("https://")})",
                    color = p.mutedForeground,
                    fontSize = 11.5.sp,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                )
            }

            if (showServerConfig) {
                Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                    FieldLabel("API BASE URL")
                    PairingTextField(
                        value = serverUrlInput,
                        onValueChange = { serverUrlInput = it },
                        placeholder = DEFAULT_API_BASE_URL,
                    )
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Text(
                            text = "Simpan URL",
                            color = p.brandDeep,
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Medium,
                            modifier = Modifier
                                .border(BorderStroke(1.dp, p.brandMid), RoundedCornerShape(7.dp))
                                .background(p.brandTint, RoundedCornerShape(7.dp))
                                .clickable {
                                    pairingStore.setApiBaseUrl(serverUrlInput)
                                    isError = false
                                    statusMessage = "API Base URL disimpan: ${pairingStore.apiBaseUrl()}"
                                }
                                .padding(horizontal = 10.dp, vertical = 5.dp),
                        )
                        Text(
                            text = "Reset Default",
                            color = p.mutedForeground,
                            fontSize = 12.sp,
                            modifier = Modifier
                                .border(BorderStroke(1.dp, p.border), RoundedCornerShape(7.dp))
                                .clickable {
                                    serverUrlInput = DEFAULT_API_BASE_URL
                                    pairingStore.setApiBaseUrl(DEFAULT_API_BASE_URL)
                                }
                                .padding(horizontal = 10.dp, vertical = 5.dp),
                        )
                    }
                }
            }

            Box(
                Modifier
                    .fillMaxWidth()
                    .height(44.dp)
                    .background(
                        if (!claiming && codeInput.isNotBlank() && deviceNameInput.isNotBlank()) {
                            Brush.linearGradient(listOf(p.brandMid, p.brandDeep))
                        } else {
                            SolidColor(p.muted)
                        },
                        RoundedCornerShape(AulaaTheme.radius),
                    )
                    .clickable(enabled = !claiming && codeInput.isNotBlank() && deviceNameInput.isNotBlank()) {
                        submitClaim(codeInput)
                    },
                contentAlignment = Alignment.Center,
            ) {
                Text(
                    text = if (claiming) "Memverifikasi kode…" else "Klaim & Hubungkan Perangkat",
                    color = if (!claiming && codeInput.isNotBlank() && deviceNameInput.isNotBlank()) p.onBrand else p.mutedForeground,
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Medium,
                )
            }
        }
    }
}

@Composable
private fun PairedSessionCard(
    session: PairingSession,
    syncing: Boolean,
    onSyncProjects: () -> Unit,
    onUnpair: () -> Unit,
) {
    val p = AulaaTheme.palette
    Column(
        modifier = Modifier
            .fillMaxWidth()
            .background(p.card, RoundedCornerShape(AulaaTheme.radiusLg))
            .border(BorderStroke(1.dp, p.border), RoundedCornerShape(AulaaTheme.radiusLg))
            .padding(14.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Box(Modifier.size(8.dp).background(p.brandMid, RoundedCornerShape(999.dp)))
            Spacer(Modifier.width(8.dp))
            Text(
                "Perangkat Aktif",
                color = p.foreground,
                fontSize = 14.sp,
                fontWeight = FontWeight.Medium,
            )
            Spacer(Modifier.weight(1f))
            Text(
                session.device.name,
                color = p.mutedForeground,
                fontSize = 12.sp,
            )
        }

        InfoRow("Merchant", session.merchant.name)
        InfoRow("Checkout URL", session.payBaseUrl)
        InfoRow("Scopes Token", session.scopes.joinToString(", "))

        Column(verticalArrangement = Arrangement.spacedBy(5.dp)) {
            FieldLabel("PROJECT TERDAFTAR (${session.projects.size})")
            if (session.projects.isEmpty()) {
                Text(
                    "Belum ada project di-cache. Tekan Sinkronkan Project.",
                    color = p.mutedForeground,
                    fontSize = 12.sp,
                )
            } else {
                session.projects.forEach { prj ->
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        modifier = Modifier
                            .fillMaxWidth()
                            .background(p.background, RoundedCornerShape(8.dp))
                            .border(BorderStroke(1.dp, p.border), RoundedCornerShape(8.dp))
                            .padding(horizontal = 10.dp, vertical = 7.dp),
                    ) {
                        Text(
                            prj.name,
                            color = p.foreground,
                            fontSize = 13.sp,
                            modifier = Modifier.weight(1f),
                        )
                        Text(
                            text = "${if (prj.isProd) "PROD" else "DEV"} · ${prj.status}",
                            color = p.mutedForeground,
                            fontSize = 11.sp,
                        )
                    }
                }
            }
        }

        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Box(
                modifier = Modifier
                    .weight(1f)
                    .height(38.dp)
                    .background(p.brandTint, RoundedCornerShape(AulaaTheme.radius))
                    .border(BorderStroke(1.dp, p.brandMid), RoundedCornerShape(AulaaTheme.radius))
                    .clickable(enabled = !syncing) { onSyncProjects() },
                contentAlignment = Alignment.Center,
            ) {
                Text(
                    text = if (syncing) "Menyinkronkan…" else "Sinkronkan Project",
                    color = p.brandDeep,
                    fontSize = 12.5.sp,
                    fontWeight = FontWeight.Medium,
                )
            }

            Box(
                modifier = Modifier
                    .weight(1f)
                    .height(38.dp)
                    .background(p.background, RoundedCornerShape(AulaaTheme.radius))
                    .border(BorderStroke(1.dp, p.border), RoundedCornerShape(AulaaTheme.radius))
                    .clickable { onUnpair() },
                contentAlignment = Alignment.Center,
            ) {
                Text(
                    text = "Putuskan Perangkat",
                    color = p.foreground,
                    fontSize = 12.5.sp,
                    fontWeight = FontWeight.Medium,
                )
            }
        }
    }
}

@Composable
private fun InfoRow(label: String, value: String) {
    val p = AulaaTheme.palette
    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.SpaceBetween,
    ) {
        Text(label, color = p.mutedForeground, fontSize = 12.sp)
        Spacer(Modifier.width(12.dp))
        Text(
            value,
            color = p.foreground,
            fontSize = 12.sp,
            maxLines = 1,
            overflow = TextOverflow.Ellipsis,
        )
    }
}

@Composable
private fun FieldLabel(text: String) {
    Text(
        text,
        color = AulaaTheme.palette.mutedForeground,
        fontSize = 11.sp,
        fontWeight = FontWeight.Medium,
    )
}

@Composable
private fun PairingTextField(
    value: String,
    onValueChange: (String) -> Unit,
    placeholder: String,
    capitalization: KeyboardCapitalization = KeyboardCapitalization.None,
) {
    val p = AulaaTheme.palette
    Box(
        Modifier
            .fillMaxWidth()
            .height(42.dp)
            .background(p.background, RoundedCornerShape(AulaaTheme.radius))
            .border(BorderStroke(1.dp, p.border), RoundedCornerShape(AulaaTheme.radius))
            .padding(horizontal = 12.dp),
        contentAlignment = Alignment.CenterStart,
    ) {
        if (value.isEmpty()) {
            Text(
                placeholder,
                color = p.mutedForeground,
                fontSize = 13.5.sp,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis,
            )
        }
        BasicTextField(
            value = value,
            onValueChange = onValueChange,
            singleLine = true,
            textStyle = TextStyle(color = p.foreground, fontSize = 13.5.sp),
            cursorBrush = SolidColor(p.brandDeep),
            keyboardOptions = KeyboardOptions(
                keyboardType = KeyboardType.Text,
                capitalization = capitalization,
            ),
            modifier = Modifier.fillMaxWidth(),
        )
    }
}

/**
 * Extracts the pairing code if the user pastes `aulaa-keyboard://pair?code=ABCDEFGH`
 * or returns the raw code otherwise.
 */
fun extractCodeFromInput(raw: String): String {
    val trimmed = raw.trim()
    if (trimmed.startsWith("aulaa-keyboard://", ignoreCase = true)) {
        val parsed = runCatching { Uri.parse(trimmed).getQueryParameter("code") }.getOrNull()
        if (!parsed.isNullOrBlank()) {
            return parsed.trim().uppercase()
        }
    }
    return trimmed
}

private fun defaultDeviceName(): String {
    val manufacturer = Build.MANUFACTURER.orEmpty().trim()
    val model = Build.MODEL.orEmpty().trim()
    val combined = if (model.startsWith(manufacturer, ignoreCase = true)) {
        model
    } else {
        "$manufacturer $model".trim()
    }
    return combined.replaceFirstChar { it.uppercase() }.ifBlank { "Android Device" }.take(100)
}
